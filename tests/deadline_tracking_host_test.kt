fun deadlineTrackingChecks() {
    val today = LocalDate.of(2026, 10, 30)
    val paperwork=ExpenseRecord(deviceId="local",dateEpochDay=today.toEpochDay(),category=ExpenseCategory.DAILY,
        amount=20.0,title="证件手续",ledgerKind="paperwork",dueEpochDay=today.plusDays(3).toEpochDay())
    check(deadlineTracks(listOf(paperwork),today).isEmpty())
    check(ledgerReminders(listOf(paperwork),today).isEmpty())
    val day = today.toEpochDay()
    val old = ExpenseRecord(id=1, deviceId="AA:BB:CC:DD:EE:91", dateEpochDay=day-300,
        category=ExpenseCategory.DAILY, amount=900.0, title="保险", ledgerKind="insurance",
        itemName="交强险", startEpochDay=day-350, dueEpochDay=day+7, party="旧公司")
    val renewal = old.copy(id=2, dateEpochDay=day-1, startEpochDay=day+8, dueEpochDay=day+373, party="新公司")
    val joined = deadlineTracks(listOf(old, renewal), today).single()
    check(joined.record.id == old.id && joined.reminderDay == renewal.dueEpochDay)
    check(joined.detail.contains("连续续保") && joined.status.contains("保障日期内"))
    check(ledgerReminders(listOf(old, renewal),today).single().deliveryStage(today) == null)
    val gap = renewal.copy(startEpochDay=day+10)
    check(deadlineTracks(listOf(old, gap),today).single().detail.contains("空档"))
    check(ledgerReminders(listOf(old,gap),today).single().offset(today)==7L)
    val missingStart = renewal.copy(startEpochDay=null)
    check(ledgerReminders(listOf(old,missingStart),today).single().offset(today)==7L)
    check(ledgerReminders(listOf(old.copy(startEpochDay=null),missingStart),today).single().offset(today)==7L)
    val expired = old.copy(dueEpochDay=day-2)
    check(ledgerReminders(listOf(expired,missingStart),today).single().deliveryStage(today)==-1L)
    check(deadlineTracks(listOf(renewal),today).single().status.contains("待生效"))
    check(ledgerReminders(listOf(renewal),today).isEmpty())
    val incomplete = renewal.copy(startEpochDay=null,dueEpochDay=null)
    check(ledgerReminders(listOf(old,incomplete),today).single().offset(today)==7L)
    check(deadlineTracks(listOf(old,renewal.copy(itemName=" 机动车交通事故责任强制保险 ")),today).size==1)
    check(deadlineTracks(listOf(old,renewal.copy(itemName="商业险")),today).size==2)
    check(deadlineTracks(listOf(old,renewal.copy(deviceId="AA:BB:CC:DD:EE:92")),today).size==2)
    check(deadlineTracks(listOf(old.copy(startEpochDay=null)),today).single().detail.contains("生效日期未知"))
    // The current urgency band catches up without replaying all missed milestones.
    val reminder = LedgerReminder("test","测试",day+29)
    check(reminder.deliveryStage(today)==30L)
    check(reminder.deliveryKey(today)==reminder.deliveryKey(today.plusDays(1)))
    check(reminder.copy(dueDay=day+6).deliveryStage(today)==7L)
    check(reminder.copy(dueDay=day+2).deliveryStage(today)==3L)
    check(reminder.copy(dueDay=day).deliveryStage(today)==0L)
    check(reminder.copy(dueDay=day-5).message(today).contains("已到期 5 天"))
    val registered = LocalDate.of(2020,2,29)
    for (age in listOf(2,4,8)) check(inspectionAction(registered,registered.plusYears(age.toLong()),true).startsWith("免上线"))
    for (age in listOf(6,10,11,16)) check(inspectionAction(registered,registered.plusYears(age.toLong()),true).startsWith("需上线"))
    check(inspectionAction(registered,registered.plusYears(6),false).contains("待核实"))
    check(inspectionAction(null,registered.plusYears(6),true).contains("待核实"))
    check(inspectionAction(registered,registered.plusYears(7),true).contains("不一致"))
    check(nextInspectionDue(registered,LocalDate.of(2026,2,28))==LocalDate.of(2028,2,29))
    check(nextInspectionDue(registered,LocalDate.of(2030,2,28))==LocalDate.of(2031,2,28))
    check(nextInspectionDue(registered,LocalDate.of(2027,2,28))==null)
    check(inspectionWindow(LocalDate.of(2027,1,31))==LocalDate.of(2026,11,1))
    val inspection = old.copy(title="年审",ledgerKind="inspection",itemName=PRIVATE_INSPECTION,
        startEpochDay=LocalDate.of(2020,12,2).toEpochDay(),dueEpochDay=LocalDate.of(2026,12,1).toEpochDay())
    val tracks = deadlineTracks(listOf(inspection),today)
    check(tracks.single().dueDay==LocalDate.of(2026,12,31).toEpochDay())
    check(tracks.single().detail.contains("需上线"))
    check(ledgerReminders(listOf(inspection),today).single().deliveryStage(today)==90L)
    check(ledgerReminders(listOf(inspection),today).single().title=="上线年检")
    val exempt = inspection.copy(startEpochDay=LocalDate.of(2022,12,2).toEpochDay())
    check(ledgerReminders(listOf(exempt),today).single().title=="免上线领标")
    val expiredInspection=inspection.copy(dueEpochDay=LocalDate.of(2026,9,30).toEpochDay())
    check(deadlineTracks(listOf(expiredInspection),today).single().dueDay==expiredInspection.dueEpochDay)
    check(ledgerReminders(listOf(expiredInspection),today).single().deliveryStage(today)==-1L)
    val manual=inspection.copy(id=3,itemName="旧手工名称",dueEpochDay=LocalDate.of(2028,12,31).toEpochDay())
    check(deadlineTracks(listOf(inspection,manual),today).size==1)
    check(deadlineTracks(listOf(manual),today).single().detail.contains("待核实"))
    check(initialInspectionDue(LocalDate.of(2026,10,15),today)==LocalDate.of(2028,10,31))
    check(initialInspectionDue(LocalDate.of(2020,4,15),today)==LocalDate.of(2026,4,30))
    check(initialInspectionDue(LocalDate.of(2020,12,15),today)==LocalDate.of(2026,12,31))
    check(initialInspectionDue(LocalDate.of(2023,4,15),today)==LocalDate.of(2027,4,30))
    check(initialInspectionDue(LocalDate.of(2010,4,15),today)==LocalDate.of(2026,4,30))
    check(annualInsuranceEnd(today)==LocalDate.of(2027,10,29))
    check(insuranceRenewalStart(today,today.minusDays(20))==today)
    check(insuranceRenewalStart(today,today.plusDays(7))==today.plusDays(8))
    check(insuranceRenewalStart(today,null)==today)
    check(annualInsuranceEnd(LocalDate.of(2023,3,1))==LocalDate.of(2024,2,29))
    check(annualInsuranceEnd(LocalDate.of(2024,2,29))==LocalDate.of(2025,2,27))
    val profile = VehicleRegistration(registered.toEpochDay(),true,LocalDate.of(2026,2,28).toEpochDay())
    check(VehicleRegistration.decode(profile.encode())==profile)
    check(VehicleRegistration.decode("broken")==null)
    val profileTracks=deadlineTracks(emptyList(),today,mapOf(old.deviceId to profile))
    check(profileTracks.single().fromVehicleInfo && profileTracks.single().dueDay==profile.inspectionDueDay)
    check(profileTracks.single().status.contains("已到期"))
    // Unrelated expense entries cannot advance the registration's pending task.
    check(deadlineTracks(listOf(manual),today,mapOf(old.deviceId to profile)).single().dueDay==profile.inspectionDueDay)
    check(deadlineTracks(listOf(manual),today,mapOf(old.deviceId to profile.copy(inspectionDueDay=null))).single().dueDay==manual.dueEpochDay)
    check(deadlineTracks(emptyList(),today.plusYears(1),mapOf(old.deviceId to profile)).single().dueDay==profile.inspectionDueDay)
    check(ledgerReminders(emptyList(),today,mapOf(old.deviceId to profile)).single().deliveryStage(today)==-1L)
    println("PASS: insurance coverage periods, renewal gaps/unknown dates, aliases/devices, inspection milestones/month windows/leap years and catch-up reminders")
}

fun vehicleRegistrationChecks(root: File) {
    val context=Context(File(root,"registration-profile"))
    val state=AppState(context)
    val first="AA:BB:CC:DD:EE:91"; val second="AA:BB:CC:DD:EE:92"
    val registered=LocalDate.of(2020,12,10)
    val profile=VehicleRegistration(registered.toEpochDay(),true,LocalDate.of(2026,12,31).toEpochDay())
    state.saveVehicleRegistration(profile)
    check(state.vehicleRegistration()==profile)
    check(TransferSchema.preferenceType(REGISTRATION_PREFIX+"local")=="string")
    check(TransferSchema.preferenceType(REGISTRATION_PREFIX+"invalid")==null)
    state.address=first
    check(state.vehicleRegistration()==profile)
    check(!state.prefs.contains(REGISTRATION_PREFIX+"local"))
    check(AppState(context).vehicleRegistration()==profile)
    state.address=second
    check(state.vehicleRegistration()==null)
    check(state.vehicleRegistration(first)==profile)
    val snapshot=TransferStore(context).snapshot()
    check(snapshot.preferences.getValue(REGISTRATION_PREFIX+first)["value"]==profile.encode())
    check(snapshot.tables.getValue("expenses").isEmpty())
    val bytes=ByteArrayOutputStream().also { TransferArchive.write(snapshot,it) }.toByteArray()
    check(TransferArchive.read(ByteArrayInputStream(bytes)).preferences==snapshot.preferences)
    val other=Context(File(root,"registration-profile-import"))
    val store=TransferStore(other)
    store.import(snapshot,true)
    check(AppState(other).vehicleRegistration(first)==profile)
    println("PASS: vehicle registration persists independently, adopts one binding only and survives archive/import without expense rows")
}
